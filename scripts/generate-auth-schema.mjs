/**
 * Regenerates src/server/db/schema/auth.ts from the Better Auth config with the
 * official generator (the `auth` CLI's API).
 *
 *   pnpm auth:generate   → then `pnpm db:generate` and review the SQL
 *
 * Why not the CLI? It refuses configs guarded by `server-only`. Why this load
 * order? tsx's resolver can't load the generator's Prisma dependency, so the
 * generator is imported natively first and tsx is registered afterwards, only
 * to load our TypeScript config (with scripts/tsconfig.json mapping
 * `server-only` to a no-op).
 */
import { writeFile } from "node:fs/promises";

import { generateDrizzleSchema } from "auth/api";
import { register } from "tsx/esm/api";

const OUTPUT = "src/server/db/schema/auth.ts";

try {
  process.loadEnvFile(".env.local");
} catch {
  // No .env.local: generation only needs the config's shape, not live services.
}

register({ tsconfig: "scripts/tsconfig.json" });
const { auth } = await import("../src/server/auth/auth.ts");
const context = await auth.$context;
const result = await generateDrizzleSchema({ file: OUTPUT, adapter: context.adapter, options: auth.options });

if (!result.code) throw new Error("Better Auth generator returned no schema");
const banner = "// Generated by `pnpm auth:generate` from src/server/auth/auth.ts. Do not edit by hand.\n";
await writeFile(OUTPUT, banner + result.code);
for (const warning of [...(result.unsafeChanges ?? []), ...(result.schemaProblems ?? [])]) console.warn(`! ${warning}`);
console.log(`wrote ${OUTPUT}`);
process.exit(0);
